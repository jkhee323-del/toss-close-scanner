"""Read-only smoke test for the deployed `main` Korean close scanner."""
from __future__ import annotations

from pathlib import Path
import pandas as pd

from .signals import compute_scored_window, pick_signals


def run(data_dir: str | Path = "data") -> dict:
    window, meta = compute_scored_window(data_dir, n_days=4)
    if window.empty:
        raise RuntimeError("No Korean signals generated by production models")
    offsets = set(window["day_offset"].astype(int))
    if offsets != {0, 1, 2, 3}:
        raise RuntimeError(f"Missing production day tabs: {offsets}")
    if meta["training_symbols"] < 100:
        raise RuntimeError("Insufficient live market coverage")
    if not window["scanner_score"].notna().all() or not window["scanner_score"].between(0, 100).all():
        raise RuntimeError("Invalid production model scores")
    for day in range(4):
        top, eligible = pick_signals(window, day, 10, 0)
        if top.empty or eligible < 10:
            raise RuntimeError(f"No usable KR scanner candidates for day {day}")
    result = {
        "as_of": str(pd.Timestamp(meta["latest_date"]).date()),
        "valid_symbols": int(meta["training_symbols"]),
        "invalid_symbols_excluded": int(meta["excluded_invalid_histories"]),
        "older_history_suffix_recovered": int(meta["recovered_recent_histories"]),
        "verified_tabs": sorted(offsets),
    }
    print(result)
    return result


if __name__ == "__main__":
    run()
